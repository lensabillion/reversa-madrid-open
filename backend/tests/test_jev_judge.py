def test_the_view_publishes_what_jev_supports_and_says_what_the_judge_did(
    tmp_path: Path,
) -> None:
    fake = FakeJev(
        answer=lambda state: (
            SUPPORTING
            if RARE in str(state["amendment_new"]) and RARE in str(state["submission_new"])
            else {**SUPPORTING, "same_legal_change": 0.1}
        )
    )
    world = collected(matching_world(tmp_path))

    view = pipeline.build_view(world, generated_at=LATER, judge=_judge(tmp_path, fake))

    published = [link for link in view.bundle.links if link.status == "published"]
    assert [link.amendment_id for link in published] == ["am:2021-0106-COD:ENVI:PE7-7"]
    assert published[0].method_revision.endswith("+jev-legal-change-v1")
    assert ("ECHOED_BY", published[0].link_id) in {
        (edge.relation, edge.link_id) for edge in view.snapshot.edges
    }
    (note,) = [text for text in view.limitations if text.startswith("Jev (")]
    assert "1 published at support >= 0.67" in note
    assert f"{len(fake.states)} asked" in note


def test_judge_links_skips_settled_links_and_reports_unjudgeable_pairs(tmp_path: Path) -> None:
    fake = FakeJev()
    long_source = SOURCE + " " + "y " * jev.MAX_REQUEST_BYTES
    long_ask = _ask(long_source[len(SOURCE) + 1 :], long_source).model_copy(
        update={"ask_id": "ask:long", "document_id": "doc:hys_attachment:long"}
    )
    links = (
        _link(status="contradicted"),
        _link().model_copy(update={"link_id": "link:open"}),
        _link().model_copy(update={"link_id": "link:long", "ask_id": "ask:long"}),
    )
    article = ArticleVersion.model_validate(
        {
            "article_id": "art:p12",
            "procedure_id": PROCEDURE,
            "document_id": "doc:cellar:proposal",
            "stage": "proposal",
            "provision": "Article 12",
            "kind": "article",
            "text": PROPOSAL,
        }
    )

    judged, note = jev_judge.judge_links(
        _judge(tmp_path, fake),
        links,
        {"am:2021-0106-COD:ENVI:7": _amendment()},
        {"ask:paper-1": _ask(), "ask:long": long_ask},
        {DOCUMENT: SOURCE, "doc:hys_attachment:long": long_source},
        [article],
    )

    assert [link.status for link in judged] == ["contradicted", "published", "unconfirmed"]
    assert judged[0] == links[0]
    assert "exceeds the request bound" in judged[2].limitations[-1]
    assert len(fake.states) == 1
    assert fake.states[0]["proposal_text"] == PROPOSAL
    assert "judged 2 pair(s) in 1 distinct request(s): 1 published" in note
    assert "1 not judged" in note


