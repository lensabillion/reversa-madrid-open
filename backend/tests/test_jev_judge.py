def test_the_atlas_command_hands_the_view_a_cached_jev_judge(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    scripted_cli(monkeypatch, matching_world(tmp_path))
    monkeypatch.setenv(cli.JEV_KEY_VARIABLE, "offline")
    real = pipeline.build_view
    judges: list[jev_judge.JevJudge | None] = []

    def offline(
        collected: pipeline.Collected,
        *,
        generated_at: datetime,
        judge: jev_judge.JevJudge | None = None,
    ) -> pipeline.AtlasView:
        judges.append(judge)
        return real(collected, generated_at=generated_at)

    monkeypatch.setattr(cli, "build_view", offline)
    args = ["atlas", AI_ACT, "--data-root", str(tmp_path), "--jev", "--jev-max-usd", "3"]

    assert cli.main(args) == 0
    (judge,) = judges
    assert judge is not None
    assert (judge.cache, judge.max_usd) == (tmp_path / "cache" / "jev", 3.0)
    assert "Atlas:" in capsys.readouterr().out
